// 3. ФУНКЦИИ
// ==========================================

function renderCards() {
  const cardsContainer = document.querySelector(".cards");
  if (!cardsContainer) return;

  cardsContainer.innerHTML = Object.entries(stories)
    .map(([id, story], index) => {
      // Чтобы задержка анимации не была слишком долгой на последних карточках,
      // мы сбрасываем ее каждый ряд (каждые 3 карточки)
      const delay = (index % 3) * 150;

      return `
        <article class="card" data-aos="fade-up" data-aos-delay="${delay}">
          <img class="card__img" src="${story.photo}" alt="Фотография семьи, ${story.location}">
          <div class="card__content">
            <h3 class="card__title">${story.title}</h3>
            <p class="card__location">${PIN_SVG}<span>${story.location}</span></p>
            <button class="card__btn" data-hero="${id}" type="button">Читать историю ${ARROW_SVG}</button>
          </div>
        </article>
      `;
    })
    .join("");
}

function initAOS() {
  if (typeof AOS !== "undefined") {
    AOS.init({
      duration: 800,
      easing: "ease-out-cubic",
      once: true,
      offset: 60,
    });
  }
}

function initSmoothScroll() {
  const headerBtn = document.querySelector(".header__btn");
  const storiesSection = document.getElementById("stories");

  if (!headerBtn || !storiesSection) return;

  headerBtn.addEventListener("click", () => {
    storiesSection.scrollIntoView({ behavior: "smooth" });
  });
}

function initModalLogic() {
  const modal = document.getElementById("storyModal");
  const cardsContainer = document.querySelector(".cards");

  if (!modal || !cardsContainer) return;

  const elements = {
    image: document.getElementById("modalImage"),
    title: document.getElementById("modalTitle"),
    location: document.getElementById("modalLocation"),
    text: document.getElementById("modalText"),
    closeBtn: document.getElementById("modalClose"),
    backBtn: document.getElementById("modalBack"),
  };

  let lastFocusedElement = null;

  function openModal(heroId) {
    const story = stories[heroId];
    if (!story) return;

    elements.image.src = story.photo;
    elements.title.textContent = story.title;
    elements.location.textContent = story.location;
    elements.text.innerHTML = story.text.map((p) => `<p>${p}</p>`).join("");

    lastFocusedElement = document.activeElement;

    modal.classList.add("is-open");
    modal.setAttribute("aria-hidden", "false");
    document.body.style.overflow = "hidden";

    // Переводим фокус на кнопку закрытия для доступности
    setTimeout(() => elements.closeBtn.focus(), 100);
  }

  function closeModal() {
    modal.classList.remove("is-open");
    modal.setAttribute("aria-hidden", "true");
    document.body.style.overflow = "";

    if (lastFocusedElement) {
      lastFocusedElement.focus();
    }
  }

  // Делегирование событий: слушаем клики на всем контейнере с карточками
  cardsContainer.addEventListener("click", (event) => {
    const btn = event.target.closest(".card__btn");
    if (btn) {
      openModal(btn.dataset.hero);
    }
  });

  // Слушатели для закрытия модалки
  elements.backBtn?.addEventListener("click", closeModal);
  elements.closeBtn?.addEventListener("click", closeModal);

  modal.addEventListener("click", (event) => {
    if (event.target === modal) closeModal();
  });

  document.addEventListener("keydown", (event) => {
    if (event.key === "Escape" && modal.classList.contains("is-open")) {
      closeModal();
    }
  });
}
